"""Network-wide sweep engine — the Rennacs take on how Shodan crawls at scale.

Shodan's defining capability isn't the UI; it's a crawler that continuously sweeps huge
address spaces, grabs banners, and keeps a fresh index. This module is the small,
readable version of that engine, with the techniques real internet scanners (zmap,
masscan) use:

* **Permuted scan order.** Instead of walking a range sequentially (which hammers one
  subnet at a time), we visit addresses in a pseudo-random permutation generated by an
  affine cycle ``(a*i + b) mod N`` with ``gcd(a, N) == 1``. That spreads load evenly
  across the whole scope and needs O(1) memory — we never materialise the host list, so
  a /16 (65k hosts) or larger streams through fine.
* **Global rate limiting.** A token-bucket caps new connections per second across the
  whole sweep, so you stay polite and within what a lab/your-own-network tolerates.
* **Bounded concurrency.** A fixed worker pool, not one task per host.
* **Resumable jobs.** A sweep is deterministic given (scope, ports, seed), so resuming
  means "skip the first K permuted indices" — checkpointed to the DB.

The authorization gate (:mod:`rennacs.authz`) is checked for the WHOLE scope up front,
so "network-wide" means the network(s) you're allowed to scan — never arbitrary public
space you don't own.
"""

from __future__ import annotations

import asyncio
import ipaddress
import random
import time
from dataclasses import dataclass, field
from math import gcd, isfinite

from . import ports as portlib
from . import scanner
from .authz import Policy
from .scanner import HostResult


@dataclass
class TargetSpace:
    """A flat, O(1)-addressable index over one or more IPv4 CIDRs.

    Maps a global index ``0..total-1`` to an IP without ever building a host list, so
    the scope can be far larger than memory.
    """

    total: int = 0
    _segs: list = field(default_factory=list)   # (base_index, count, first_ip_int)

    @classmethod
    def from_scope(cls, scope: str) -> "TargetSpace":
        space = cls()
        for part in scope.split(","):
            part = part.strip()
            if not part:
                continue
            net = ipaddress.ip_network(part, strict=False)
            if net.version != 4:
                raise ValueError("sweep supports IPv4 ranges only")
            if net.num_addresses <= 2:          # /31, /32: every address is usable
                first = int(net.network_address)
                count = net.num_addresses
            else:                                # skip network + broadcast
                first = int(net.network_address) + 1
                count = net.num_addresses - 2
            space._segs.append((space.total, count, first))
            space.total += count
        return space

    def networks(self) -> list:
        return [str(ipaddress.ip_address(first)) for _, _, first in self._segs]

    def addr(self, global_idx: int) -> str:
        for base, count, first in self._segs:
            if global_idx < base + count:
                return str(ipaddress.ip_address(first + (global_idx - base)))
        raise IndexError(global_idx)


def permutation(total: int, seed: int):
    """Return a function perm: [0,total) -> [0,total), a full-cycle permutation.

    Uses an affine map (a*i + b) mod total with a coprime to total — the memory-free
    way real scanners randomise the address space.
    """
    if total <= 1:
        return lambda i: i
    rnd = random.Random(seed)
    a = rnd.randrange(1, total)
    while gcd(a, total) != 1:
        a = a + 1 if a + 1 < total else 1
    b = rnd.randrange(0, total)
    return lambda i: (a * i + b) % total


class RateLimiter:
    """Refill at ``rate``/second, with a ``max(1, rate)`` initial burst.

    Zero disables throttling; positive fractional rates still permit whole tokens.
    """

    def __init__(self, rate: float):
        try:
            self.rate = float(rate)
        except (TypeError, ValueError) as exc:
            raise ValueError("rate must be a finite nonnegative number (0 = unlimited)") from exc
        if not isfinite(self.rate) or self.rate < 0:
            raise ValueError("rate must be finite and nonnegative (0 = unlimited)")
        self.capacity = max(1.0, self.rate)
        self.tokens = self.capacity
        self.updated = time.monotonic()
        self._lock = asyncio.Lock()

    async def acquire(self) -> None:
        if not self.rate:
            return
        async with self._lock:
            while True:
                now = time.monotonic()
                self.tokens = min(self.capacity, self.tokens + (now - self.updated) * self.rate)
                self.updated = now
                if self.tokens >= 1:
                    self.tokens -= 1
                    return
                await asyncio.sleep((1 - self.tokens) / self.rate)


@dataclass
class SweepStats:
    """Completion totals plus a crash-safe checkpoint of the ordered prefix.

    ``scanned`` includes ``start_at`` for compatibility; ``hosts_up``/``services``
    count all completed results in this invocation. ``resume_at`` is an absolute
    index, while ``resume_hosts_up``/``resume_services`` count only this invocation's
    contiguous prefix. Add the latter to the previously persisted prefix counters.
    """

    total: int = 0
    scanned: int = 0
    hosts_up: int = 0
    services: int = 0
    resume_at: int = 0   # contiguous completed prefix, not a completion count
    resume_hosts_up: int = 0  # prefix counters for this invocation only
    resume_services: int = 0


async def _scan_one(ip: str, port_list: list[int], limiter: RateLimiter,
                    timeout: float) -> HostResult:
    """Scan one host across all ports, throttled by the shared limiter."""
    services = []
    for p in port_list:
        await limiter.acquire()
        r = await scanner._grab(ip, p, timeout)
        if r is not None:
            services.append(r)
    services.sort(key=lambda s: s.port)
    return HostResult(ip=ip, services=services, scanned_ports=list(port_list))


async def sweep(scope: str, port_spec: str = "top20", *, policy: Policy | None = None,
                rate: float = 500, concurrency: int = 200, timeout: float = 2.0,
                shuffle: bool = True, seed: int | None = None, start_at: int = 0,
                on_host=None, on_progress=None, progress_every: int = 50) -> SweepStats:
    """Sweep ``scope`` (CIDR / comma list) across ``port_spec``.

    ``policy`` gates the whole scope up front. ``on_host(HostResult)`` streams every
    completed host, including results with no observed services; its successful
    return precedes checkpoint advancement. ``on_progress(SweepStats, seed)`` fires
    every ``progress_every`` completions and once at normal completion.

    Resume with ``start_at=stats.resume_at`` and the same scope, ports, shuffle mode
    and seed. ``stats.scanned`` is a completion count, NOT a safe cursor. Persist the
    previous prefix counters plus ``stats.resume_hosts_up``/``stats.resume_services``;
    out-of-order results may be replayed and callbacks must tolerate duplicates.
    Returns final :class:`SweepStats`.
    """
    policy = policy or Policy()
    port_list = portlib.resolve(port_spec)
    space = TargetSpace.from_scope(scope)
    if type(start_at) is not int or not 0 <= start_at <= space.total:
        raise ValueError("start_at must be an integer within the target space")
    if type(concurrency) is not int or concurrency <= 0:
        raise ValueError("concurrency must be a positive integer")
    if type(progress_every) is not int or progress_every <= 0:
        raise ValueError("progress_every must be a positive integer")
    scanner._check_timeout(timeout)

    # Gate every CIDR in the scope before touching the network.
    for part in scope.split(","):
        part = part.strip()
        if part:
            policy.check_network(ipaddress.ip_network(part, strict=False))

    if seed is None:
        seed = random.randrange(1, 2**31) if shuffle else 0
    perm = permutation(space.total, seed) if shuffle else (lambda i: i)

    limiter = RateLimiter(rate)
    stats = SweepStats(total=space.total, scanned=start_at, resume_at=start_at)
    next_index = start_at
    completed: dict[int, tuple[int, int]] = {}
    worker_count = max(1, min(concurrency, space.total))
    condition = asyncio.Condition()

    async def worker():
        nonlocal next_index
        while True:
            async with condition:
                # Bound both outstanding work and completed holes behind a straggler.
                await condition.wait_for(lambda: next_index >= space.total or
                                         next_index < stats.resume_at + worker_count)
                i = next_index
                if i >= space.total:
                    return
                next_index = i + 1
            ip = space.addr(perm(i))
            hr = await _scan_one(ip, port_list, limiter, timeout)
            async with condition:
                hosts_up, services = int(bool(hr.services)), len(hr.services)
                stats.scanned += 1
                stats.hosts_up += hosts_up
                stats.services += services
                if on_host:
                    on_host(hr)
                completed[i] = (hosts_up, services)
                while stats.resume_at in completed:
                    hosts_up, services = completed.pop(stats.resume_at)
                    stats.resume_hosts_up += hosts_up
                    stats.resume_services += services
                    stats.resume_at += 1
                condition.notify_all()
                if on_progress and stats.scanned % progress_every == 0:
                    on_progress(stats, seed)

    workers = [asyncio.create_task(worker())
               for _ in range(worker_count)]
    try:
        await asyncio.gather(*workers)
    finally:
        for task in workers:
            if not task.done():
                task.cancel()
        await asyncio.gather(*workers, return_exceptions=True)
    if on_progress:
        on_progress(stats, seed)
    return stats
